// Material 3 colour schemes for the btui toolkit, generated with Google's
// material-color-utilities (Apache-2.0; npm @material/material-color-utilities)
// from the brand: plum #7a3e8e is the seed (TONAL_SPOT roles over a primary
// palette kept at the brand chroma rather than desaturated), coral #e07a5f is the tertiary
// key colour, and three custom colours (warning, success, info) are harmonised
// towards the seed the way M3 "custom colors" are.
//
//   npm install @material/material-color-utilities@0.3.0   (0.4.0 ships a broken import)
//   node tools/make_theme.mjs <path to that package> > ui/theme_gen.dado
import { pathToFileURL } from 'node:url';
import path from 'node:path';

const lib = await import(pathToFileURL(path.join(process.argv[2], 'index.js')).href);
const { Variant } = await import(pathToFileURL(path.join(process.argv[2], 'dynamiccolor', 'variant.js')).href);
const { Hct, DynamicScheme, TonalPalette, MaterialDynamicColors, Blend, hexFromArgb, argbFromHex } = lib;

const SEED = '#7a3e8e';
const CORAL = '#e07a5f';
const CUSTOM = { warning: '#e8a317', success: '#2e7d32', info: '#1e6fb8' };

const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceDim', 'surfaceBright', 'surfaceContainerLowest', 'surfaceContainerLow',
  'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
  'inverseSurface', 'inverseOnSurface', 'outline', 'outlineVariant', 'shadow', 'scrim',
  'surfaceTint',
];

const snake = (s) => s.replace(/[A-Z]/g, (c) => '_' + c.toLowerCase());
const hex = (argb) => '0x' + hexFromArgb(argb).slice(1).toLowerCase();

function scheme(dark) {
  const seed = Hct.fromInt(argbFromHex(SEED));
  return new DynamicScheme({
    sourceColorArgb: argbFromHex(SEED),
    variant: Variant.TONAL_SPOT,
    contrastLevel: 0,
    isDark: dark,
    primaryPalette: TonalPalette.fromHueAndChroma(seed.hue, Math.max(seed.chroma, 48)),
    secondaryPalette: TonalPalette.fromHueAndChroma(seed.hue, 16),
    tertiaryPalette: TonalPalette.fromInt(argbFromHex(CORAL)),
    neutralPalette: TonalPalette.fromHueAndChroma(seed.hue, 5),
    neutralVariantPalette: TonalPalette.fromHueAndChroma(seed.hue, 9),
  });
}

const out = [];
out.push('// beautalks - radio programming software');
out.push('// Copyright (C) 2026 Anaxarchus. Licensed under the GNU GPL v3 or later.');
out.push('//');
out.push('// GENERATED by tools/make_theme.mjs (material-color-utilities). Do not edit.');
out.push(`// Seed ${SEED} (plum; TONAL_SPOT role mapping over a brand-chroma primary palette), tertiary key ${CORAL} (coral); custom colours`);
out.push(`// warning ${CUSTOM.warning}, success ${CUSTOM.success}, info ${CUSTOM.info}, harmonised to the seed.`);
out.push('package btui');
out.push('');
out.push('// Fill `s` with the Material 3 roles for the light or the dark scheme.');
out.push('void gen_scheme(^Scheme s, bool dark):');
for (const dark of [false, true]) {
  out.push(dark ? '    else:' : '    if !dark:');
  const sc = scheme(dark);
  for (const r of ROLES) {
    out.push(`        s.${snake(r)} = rgb(${hex(MaterialDynamicColors[r].getArgb(sc))})`);
  }
  for (const [name, src] of Object.entries(CUSTOM)) {
    const pal = TonalPalette.fromInt(Blend.harmonize(argbFromHex(src), argbFromHex(SEED)));
    const t = dark ? [80, 20, 30, 90] : [40, 100, 90, 10];
    out.push(`        s.${name} = rgb(${hex(pal.tone(t[0]))})`);
    out.push(`        s.on_${name} = rgb(${hex(pal.tone(t[1]))})`);
    out.push(`        s.${name}_container = rgb(${hex(pal.tone(t[2]))})`);
    out.push(`        s.on_${name}_container = rgb(${hex(pal.tone(t[3]))})`);
  }
}
console.log(out.join('\n'));
